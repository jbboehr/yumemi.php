$phpDocParserPrefix = 'PHPStan\\PhpDocParser\\';
$phpDocParserSource = sprintf(
    'phar://%s/vendor/phpstan/phpdoc-parser/src/',
    __DIR__ . '/vendor/phpstan/phpstan/phpstan.phar',
);

spl_autoload_register(static function (string $class) use ($phpDocParserPrefix, $phpDocParserSource): void {
    if (!str_starts_with($class, $phpDocParserPrefix)) {
        return;
    }

    $relativePath = substr($class, strlen($phpDocParserPrefix));
    $path = $phpDocParserSource . str_replace('\\', '/', $relativePath) . '.php';
    if (is_file($path)) {
        require $path;
    }
}, true, true);
