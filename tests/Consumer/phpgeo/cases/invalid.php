declare(strict_types=1);

use Location\Bearing\BearingSpherical;
use Location\Coordinate;
use Location\Distance\Vincenty;

use function jbboehr\Yumemi\unit;

/** @param unit_float<'second'> $duration */
function savePhpGeoDuration(float $duration): void
{
}

$start = new Coordinate(unit(0.0, 'meter'), unit(0.0, 'degree'));
$end = new Coordinate(unit(0.0, 'degree'), unit(1.0, 'degree'));
$distance = (new Vincenty())->getDistance($start, $end);

savePhpGeoDuration($distance);

(new BearingSpherical())->calculateDestination(
    $start,
    unit(90.0, 'meter'),
    unit(1_000.0, 'degree'),
);
